// Content entry for app.getbee.io frames (the drag-and-drop editor). Runs in every frame;
// mounts frame:'bee' features, but only in frames an Iterable app page embeds (app.getbee.io also
// serves Beefree's own site and other customers' editors; see classifyEmbedding). No project detection here, and no API access: the background only
// accepts wb:open-options from app.getbee.io frames (ctx.api answers with an error locally).

import { MSG } from '../core/messages.js';
import * as settings from '../core/settings.js';
import { createRouter } from '../core/router.js';
import { createLogger, setDebug } from '../core/log.js';
import { FEATURES, getMeta } from '../features/registry.js';
// Generated by scripts/build.mjs: features whose meta.frame is 'bee' (index.js), plus the bee
// companions (bee.js) of features homed in the top frame (meta.companionFrames).
import IMPLS from 'wb-virtual:impls/bee';
import { injectPageFonts } from '../ui/fonts.js';
import { watchGeneralSettings } from '../ui/theme.js';
import { makeContext } from './context.js';
import { classifyEmbedding, EMBED_HELLO_TIMEOUT_MS, APP_ORIGINS } from '../core/api-validation.js';
import { waitForEmbedHello } from './embed-handshake.js';
import { createBeeHub, beeChannelOrigin } from '../core/frames.js';
import { createPageHub } from '../core/page-rpc.js';
// Generated by scripts/build.mjs: true only when some bee-frame feature ships a main.js (then
// main-world-bee.js runs in these frames too).
import HAS_BEE_MAIN from 'wb-virtual:has-main/bee';

const log = createLogger('bee');

function isTopFrame() {
  try { return window.top === window; } catch { return false; } // cross-origin top: still a frame
}

function embedding() {
  const ao = globalThis.location?.ancestorOrigins;
  let ancestorOrigins = null;
  try { if (ao && typeof ao.length === 'number') ancestorOrigins = Array.from(ao, String); } catch { ancestorOrigins = null; }
  return { ancestorOrigins, referrer: document.referrer, isTop: isTopFrame() };
}

/** Log why this frame stays dormant. Loads general.debug first: it runs before watchGeneralSettings. */
function dormant(why, { ancestorOrigins, referrer }) {
  let ref = '(none)';
  try { if (referrer) ref = new URL(referrer).origin; } catch { ref = '(unparseable)'; } // origin only: no paths/queries in logs
  settings.load()
    .then((s) => { setDebug(s.general.debug); log.debug(`embed: ${why}; not starting`, { ancestorOrigins, referrerOrigin: ref }); })
    .catch(() => {});
}

/**
 * The "can't tell" case (e.g. Firefox reports "null" ancestors for a no-referrer <iframe>, and the
 * referrer is empty too): wait for content/app.js in the Iterable top page to announce itself.
 * acceptEmbedHello checks event.origin (browser-set, unforgeable by a non-Iterable embedder) and
 * that the sender is our parent and the top page. Never starts on timeout.
 */
function awaitEmbedHello(input) {
  waitForEmbedHello({
    win: window,
    onAccept: (origin) => {
      start(origin);
      watchGeneralSettings().then(() => log.debug('embed: confirmed by the Iterable page handshake', origin)).catch(() => {});
    },
    onTimeout: () => dormant(`no handshake from an Iterable parent within ${EMBED_HELLO_TIMEOUT_MS / 1000} s`, input),
  });
}

function gate() {
  if (window.__wbBeeStarted || window.__wbBeeGated) return;
  window.__wbBeeGated = true;
  const input = embedding();
  const kind = classifyEmbedding(input);
  if (kind === 'iterable') { start(verifiedParentOrigin(input)); return; }
  if (kind === 'unknown') { awaitEmbedHello(input); return; }
  dormant('not embedded by an Iterable app page', input); // 'other': refuse without waiting
}

/**
 * For the frame channel: the Iterable origin of this frame's parent, when the embedding check
 * established it. ancestorOrigins[0] is the parent; with no ancestor list (older Firefox), the
 * app-origin referrer classifyEmbedding accepted. A nested bee frame (parent is not an Iterable
 * page) gets null: no channel.
 */
function verifiedParentOrigin({ ancestorOrigins, referrer }) {
  if (Array.isArray(ancestorOrigins) && ancestorOrigins.length) {
    return APP_ORIGINS.includes(ancestorOrigins[0]) ? ancestorOrigins[0] : null;
  }
  try { const o = new URL(referrer).origin; return APP_ORIGINS.includes(o) ? o : null; } catch { return null; }
}

function parentIsTop() {
  try { return window.parent !== window && window.parent === window.top; } catch { return false; }
}

function start(verifiedOrigin = null) {
  if (window.__wbBeeStarted) return;
  window.__wbBeeStarted = true;

  injectPageFonts();
  watchGeneralSettings();

  // Frame channel to the Iterable top page (ARCHITECTURE §6.2): only for a direct child of the
  // top page whose Iterable origin was verified above; otherwise ctx.frames is inert.
  const frames = createBeeHub({
    win: window, log,
    parentOrigin: beeChannelOrigin({ verifiedOrigin, parentIsTop: parentIsTop() }),
  });
  frames.start();
  const page = HAS_BEE_MAIN ? createPageHub({ available: true, log }) : null;

  const router = createRouter({
    frame: 'bee',
    metas: FEATURES,
    impls: IMPLS,
    makeCtx: (meta, base) => makeContext(meta, base, { project: null, frame: 'bee', frames, page }),
    loadSettings: settings.load,
    subscribeSettings: settings.subscribe,
  });
  router.start().catch((e) => log.error('router failed to start', e));

  chrome.runtime.onMessage.addListener((msg, sender, sendResponse) => {
    if (sender.id !== chrome.runtime.id || msg?.type !== MSG.FEATURE_ACTION) return false;
    const meta = getMeta(msg.featureId);
    if (!meta || meta.frame !== 'bee') return false; // actions go to the home frame only
    // Only a frame that actually handled it answers; other frames stay silent.
    if (!router.dispatchAction(msg.featureId, msg.action)) return false;
    sendResponse({ ok: true });
    return false;
  });
}

gate();
