async function handleApi(msg) {
  const v = validateApiRequest(msg);
  if (!v.ok) return apiFail(API_ERROR.BAD_REQUEST, v.message);
  const entry = await getKeyForUse(v.value.projectKey);
  if (!entry) return apiFail(API_ERROR.NO_KEY, 'No API key saved for this project. Add one in Workbench settings.');
  // The host comes from the projectKey; the stored entry must agree (keys.js enforces this on write).
  if (entry.dataCenter !== v.value.dataCenter) return apiFail(API_ERROR.NO_KEY, 'Saved key does not match this project\u2019s data center.');
  return performApiRequest(v.value, entry.apiKey);
}

async function handleKeysStatus(msg) {
  const s = await getStatus(msg.projectKey);
  return { hasKey: s.hasKey, masked: s.masked, name: s.name };
}

/** Transient outcomes (network, timeout, 429, 5xx) say nothing about the key, so they aren't recorded. */
function isDefinitiveTest(res) {
  if (!res.error) return true;
  if (res.error.code !== API_ERROR.HTTP) return false;
  return res.status >= 400 && res.status < 500 && res.status !== 429;
}

async function handleKeysTest(msg) {
  const pk = parseProjectKey(msg.projectKey);
  if (!pk) return { ok: false, status: 0, message: 'Project key is malformed.' };
  const entry = await getKeyForUse(msg.projectKey);
  if (!entry) return { ok: false, status: 0, message: describeKeyTest({ ok: false, errorCode: API_ERROR.NO_KEY }) };
  const v = validateApiRequest({ projectKey: msg.projectKey, method: 'GET', path: KEY_TEST_PATH, timeoutMs: KEY_TEST_TIMEOUT_MS });
  if (!v.ok) return { ok: false, status: 0, message: 'Internal error building the test request.' };
  const res = await performApiRequest(v.value, entry.apiKey);
  const message = describeKeyTest({
    ok: res.ok, status: res.status, errorCode: res.error && res.error.code, dataCenter: pk.dataCenter,
  });
  if (isDefinitiveTest(res)) {
    try {
      await recordTest(msg.projectKey, { ok: res.ok, status: res.status, savedAt: entry.savedAt });
    } catch { /* result is still reported to the caller */ }
  }
  return { ok: res.ok, status: res.status, message };
}

async function findOptionsTab(baseUrl) {
  // Chrome 116+: runtime.getContexts sees our own pages without the "tabs" permission.
  if (typeof chrome.runtime.getContexts === 'function') {
    try {
      const ctxs = await chrome.runtime.getContexts({ contextTypes: ['TAB'] });
      const hit = ctxs.find((c) => typeof c.documentUrl === 'string' && c.documentUrl.split('#')[0] === baseUrl && c.tabId >= 0);
      if (hit) return { tabId: hit.tabId, windowId: hit.windowId };
      return null;
    } catch { /* fall through */ }
  }
  // Firefox: tab.url is only visible where the browser lets us see it; otherwise we open a new tab.
  try {
    const tabs = await chrome.tabs.query({});
    const hit = tabs.find((t) => typeof t.url === 'string' && t.url.split('#')[0] === baseUrl);
    if (hit) return { tabId: hit.id, windowId: hit.windowId };
  } catch { /* ignore */ }
  return null;
}

async function handleOpenOptions(msg) {
  const hash = buildOptionsHash(msg.section, msg.params);
  if (hash === null) return { ok: false, error: { code: API_ERROR.BAD_REQUEST, message: 'Invalid settings section or parameters.' } };

  const base = chrome.runtime.getURL('options.html');
  const target = base + hash;
  const existing = await findOptionsTab(base);
  if (existing) {
    await chrome.tabs.update(existing.tabId, hash ? { active: true, url: target } : { active: true });
    if (existing.windowId != null && chrome.windows?.update) {
      try { await chrome.windows.update(existing.windowId, { focused: true }); } catch { /* ignore */ }
    }
  } else {
    await chrome.tabs.create({ url: target });
  }
  return { ok: true };
}

