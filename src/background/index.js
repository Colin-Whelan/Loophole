/** Largest response body relayed back to a content script (Chrome's message cap is 64 MiB). */
const MAX_RESPONSE_BYTES = 32 * 1024 * 1024;
/**
 * Key test endpoint. GET /api/channels is read-only, takes no parameters, returns a few hundred
 * bytes with no PII, and is callable by every server-side key type (full or read-only). Mobile
 * and JavaScript keys are refused, which is the right answer: they can't do Workbench's jobs.
 */
const KEY_TEST_PATH = '/api/channels';
const KEY_TEST_TIMEOUT_MS = 15_000;

// ---------------------------------------------------------------------------
// Response helpers
// ---------------------------------------------------------------------------

function apiFail(code, message, status = 0) {
  return { ok: false, status, error: { code, message } };
}

function safeErrorText(err) {
  // Error messages from fetch/streams never contain request headers, but keep them short.
  return String((err && err.message) || err || 'unknown error').slice(0, 200);
}

class ResponseTooLarge extends Error {}

async function readTextCapped(resp, maxBytes) {
  const declared = Number(resp.headers.get('content-length'));
  if (Number.isFinite(declared) && declared > maxBytes) throw new ResponseTooLarge();
  if (!resp.body || typeof resp.body.getReader !== 'function') {
    const t = await resp.text();
    if (t.length > maxBytes) throw new ResponseTooLarge();
    return t;
  }
  const reader = resp.body.getReader();
  const decoder = new TextDecoder();
  let total = 0;
  let out = '';
  for (;;) {
    const { done, value } = await reader.read();
    if (done) break;
    total += value.byteLength;
    if (total > maxBytes) {
      try { await reader.cancel(); } catch { /* ignore */ }
      throw new ResponseTooLarge();
    }
    out += decoder.decode(value, { stream: true });
  }
  return out + decoder.decode();
}

// Chrome may stop an idle extension service worker, including one waiting more than 30 s for a
// fetch() response. Requests may run for up to 120 s (bulk endpoints), so while any are in flight
// we make a trivial extension API call every 20 s, which resets the idle timer (Chrome 110+).
// Harmless on a Firefox event page.
let inFlight = 0;
let keepAliveTimer = null;

function keepAliveStart() {
  if (inFlight++ > 0) return;
  keepAliveTimer = setInterval(() => {
    try {
      const p = chrome.runtime.getPlatformInfo?.();
      if (p && typeof p.catch === 'function') p.catch(() => {});
    } catch { /* ignore */ }
  }, 20_000);
}

function keepAliveStop() {
  if (--inFlight > 0) return;
  inFlight = 0;
  clearInterval(keepAliveTimer);
  keepAliveTimer = null;
}

/**
 * Perform one validated request. `req` is validateApiRequest(...).value.
 * Always resolves to { ok, status, data?, retryAfterMs?, error? }.
 */
async function performApiRequest(req, apiKey) {
  keepAliveStart();
  try {
    return await doFetch(req, apiKey);
  } finally {
    keepAliveStop();
  }
}

async function doFetch(req, apiKey) {
  const ctrl = new AbortController();
  const timer = setTimeout(() => ctrl.abort(), req.timeoutMs);
  const headers = { 'Api-Key': apiKey, Accept: 'application/json' };
  if (req.bodyJson != null) headers['Content-Type'] = 'application/json';

  try {
    let resp;
    try {
      resp = await globalThis.fetch(req.url, {
        method: req.method,
        headers,
        body: req.bodyJson ?? undefined,
        signal: ctrl.signal,
        credentials: 'omit',        // never attach cookies to api.iterable.com
        redirect: 'error',          // custom headers survive cross-origin redirects; don't follow any
        cache: 'no-store',
        referrerPolicy: 'no-referrer',
      });
    } catch (err) {
      if (ctrl.signal.aborted) return apiFail(API_ERROR.TIMEOUT, `No response within ${Math.round(req.timeoutMs / 1000)}s.`);
      return apiFail(API_ERROR.NETWORK, 'Network error: ' + safeErrorText(err));
    }

    const retryAfterMs = parseRetryAfter(resp.headers.get('retry-after'));
    let text;
    try {
      text = await readTextCapped(resp, MAX_RESPONSE_BYTES);
    } catch (err) {
      // NETWORK / TIMEOUT always carry status 0 (§6), even though a status line arrived: callers
      // tell "outcome unknown" apart by status 0 + code (core/retry.js isOutcomeUnknown), and a
      // 200 whose body never arrived must not look like an HTTP answer.
      if (err instanceof ResponseTooLarge) {
        return apiFail(API_ERROR.NETWORK, `Response larger than ${MAX_RESPONSE_BYTES / 1024 / 1024} MiB; not relayed (HTTP ${resp.status}).`);
      }
      if (ctrl.signal.aborted) return apiFail(API_ERROR.TIMEOUT, `Response not complete within ${Math.round(req.timeoutMs / 1000)}s (HTTP ${resp.status}).`);
      return apiFail(API_ERROR.NETWORK, `Network error while reading the response (HTTP ${resp.status}): ` + safeErrorText(err));
    }

    // Last line of defense: if the server ever echoes the key back, it doesn't leave the background.
    text = redactSecret(text, apiKey);
    let data = null;
    if (text) {
      try { data = JSON.parse(text); } catch { data = text; }
    }

    const out = { ok: resp.ok, status: resp.status, data };
    if (retryAfterMs !== undefined) out.retryAfterMs = retryAfterMs;
    if (!resp.ok) out.error = { code: API_ERROR.HTTP, message: describeHttpError(resp.status, data) };
    return out;
  } finally {
    clearTimeout(timer);
  }
}

