// Background: Chrome MV3 service worker / Firefox MV3 event page (same bundle for both).
// Message router, Iterable API proxy, key status/test, options-page opener, onboarding, and the
// runtime registration of optional-permission content scripts (frame:'auth' features).
// Contract: docs/ARCHITECTURE.md §4, §6 and §9.
//
// Rules for this file:
//  - No DOM, no `window`: it must run as a service worker.
//  - Listeners are registered synchronously at top level so a woken worker sees the event.
//  - The raw API key only ever goes into the outgoing `Api-Key` header. It is never returned,
//    logged, or put in an error message; response text is scrubbed of it as a last line of defense.
//  - No retries here. Retry policy belongs to the feature (core/retry.js).

