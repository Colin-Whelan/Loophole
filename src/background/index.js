// Router
// ---------------------------------------------------------------------------

const HANDLERS = {
  [MSG.API]: handleApi,
  [MSG.KEYS_STATUS]: handleKeysStatus,
  [MSG.KEYS_TEST]: handleKeysTest,
  [MSG.OPEN_OPTIONS]: handleOpenOptions,
};

/** The response a type returns when its handler can't run, in that type's own shape. */
function failureFor(type, code, message) {
  switch (type) {
    case MSG.API: return apiFail(code, message);
    case MSG.KEYS_STATUS: return { hasKey: false, masked: '', name: '', error: { code, message } };
    case MSG.KEYS_TEST: return { ok: false, status: 0, message };
    default: return { ok: false, error: { code, message } };
  }
}

function onMessage(msg, sender, sendResponse) {
  if (!msg || typeof msg !== 'object' || typeof msg.type !== 'string') return false;
  if (!Object.hasOwn(HANDLERS, msg.type)) return false; // not ours (or popup→content traffic)

  const kind = classifySender(sender, {
    runtimeId: chrome.runtime.id,
    extensionBaseUrl: chrome.runtime.getURL(''),
  });
  if (!kind) return false; // unknown sender: ignore silently
  if (!senderAllowed(msg.type, kind)) {
    sendResponse(failureFor(msg.type, API_ERROR.BAD_REQUEST, 'This request is not allowed from here.'));
    return false;
  }

  // `return true` + sendResponse works in both Chrome and Firefox MV3 (Chrome only recently
  // learned to accept a returned Promise).
  Promise.resolve()
    .then(() => HANDLERS[msg.type](msg, sender, kind))
    .then(
      (res) => sendResponse(res),
      (err) => {
        // Messages from keys.js / fetch never contain the key; still don't log request details.
        console.warn('[WB:bg]', msg.type, 'failed:', err && err.name, safeErrorText(err));
        sendResponse(failureFor(msg.type, API_ERROR.NETWORK, 'Workbench background error: ' + safeErrorText(err)));
      },
    );
  return true;
}

function onInstalled(details) {
  if (details && details.reason === 'install') {
    chrome.tabs.create({ url: chrome.runtime.getURL('options.html#welcome') }).catch(() => {});
  }
  // A new version may ship mappers for scripts whose settings were stashed at import time
  // (wb:legacy:*, ARCHITECTURE §8.4). The options page also runs this on every load.
  if (details && details.reason === 'update') {
    runStashedMappers(importers, { announced: false }).then(
      (done) => { if (done.length) console.info('[WB:bg] imported stashed settings for', done.map((d) => d.featureId).join(', ')); },
      (err) => console.warn('[WB:bg] stashed-settings import failed:', safeErrorText(err)),
    );
  }
}

// ---------------------------------------------------------------------------
// Optional-permission content scripts (frame:'auth')
// ---------------------------------------------------------------------------
//
// content-auth.js is registered at runtime for exactly (enabled frame:'auth' features ∩ granted
// optional origins), never listed in the static manifest (that would make the host required).
// Re-synced on every background start (a service worker / event page wakes often; the diff makes
// that cheap and idempotent) and whenever settings or permissions change. Registrations use
// persistAcrossSessions, but nothing relies on it: a browser that drops them (or keeps a stale
// one) is corrected by the next start.

let syncChain = Promise.resolve();
let syncQueued = false;

function scheduleScriptSync(reason) {
  if (syncQueued) return syncChain;
  syncQueued = true;
  syncChain = syncChain
    .then(() => { syncQueued = false; return syncOptionalScripts(); })
    .then(
      (plan) => { if (plan && (plan.unregister.length || plan.register.length)) console.info('[WB:bg] content scripts synced (' + reason + '):', JSON.stringify(plan.register.map((s) => ({ id: s.id, matches: s.matches }))), 'removed', JSON.stringify(plan.unregister)); },
      (err) => console.warn('[WB:bg] content script sync failed (' + reason + '):', safeErrorText(err)),
    );
  return syncChain;
}

async function syncOptionalScripts() {
  // Built without any frame:'auth' feature → no "scripting" permission and nothing to register.
  if (!chrome.scripting?.registerContentScripts) return null;
  const metas = FEATURES.filter((m) => homeFrame(m) === 'auth');
  const resolved = await settings.load();
  const granted = new Set();
  for (const origin of new Set(metas.flatMap(featureOrigins))) {
    try { if (await chrome.permissions.contains({ origins: [origin] })) granted.add(origin); } catch { /* not granted */ }
  }
  const desired = desiredAuthScripts({ metas, settings: resolved, granted });
  const current = await chrome.scripting.getRegisteredContentScripts();
  const plan = planScriptSync(current, desired);
  if (plan.unregister.length) await chrome.scripting.unregisterContentScripts({ ids: plan.unregister });
  if (plan.register.length) await chrome.scripting.registerContentScripts(plan.register);
  return plan;
}

function onStorageChanged(changes, areaName) {
  if (areaName === 'local' && changes && Object.hasOwn(changes, STORAGE.SETTINGS)) scheduleScriptSync('settings changed');
}

chrome.runtime.onMessage.addListener(onMessage);
chrome.runtime.onInstalled.addListener(onInstalled);
chrome.storage.onChanged.addListener(onStorageChanged);
chrome.permissions.onAdded.addListener(() => scheduleScriptSync('permission granted'));
chrome.permissions.onRemoved.addListener(() => scheduleScriptSync('permission removed'));
scheduleScriptSync('background start');
